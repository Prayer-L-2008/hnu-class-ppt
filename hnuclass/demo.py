# -*- coding: utf-8 -*-
"""内置示例：没有账号也能看到成品长什么样。"""
from __future__ import annotations

from .model import Case, CodePage, Deck, Problem


def demo_deck() -> Deck:
    p1 = Problem(
        assignment="期中", ptype="编程题", title="拯救艾泽拉斯大陆的勇士",
        description=(
            "传说在遥远的艾泽拉斯大陆，巫妖王统帅着亡灵大军进攻人类最后的净土。"
            "你作为人类最后的希望，被传送到世界之树中寻找足够的魔法值。\n"
            "世界之树是一个由 M×N 个密室组成的迷宫，你从左上角 (0,0) 出发，"
            "只能朝上、下、左、右四个方向走一步，终点在 (M-1,N-1)。\n"
            "每个密室会强制扣除相应的生命点数，并赐予该密室的魔力值；"
            "魔法值为奇数时额外获得 3 点魔法值，为偶数时额外获得 3 点生命值。"
        ),
        input_form="第一行两个整数 M、N，接下来 M 行每行 N 个非负整数表示密室魔力值。",
        output_form="输出一个整数，表示在生命值不耗尽的前提下能获得的最大魔法值。",
        samples=[Case("3 3\n1 2 3\n4 5 6\n7 8 9", "12"),
                 Case("2 2\n0 0\n0 0", "0")],
        analysis=[
            "这道题的本质是在网格图上找一条从左上到右下的路径，并最大化路径上的收益。"
            "因为每个格子只能进入一次、且四个方向都能走，用 DFS 枚举所有简单路径是最直接的建模方式。",
            "搜索时维护三个量：当前位置 (x,y)、当前生命值 hp、当前累计魔法值 sum。"
            "进入一个格子前先结算它的奖励或扣除，再判断 hp 是否仍然大于 0，不满足就剪枝回溯。",
            "终点处用 sum 更新全局最大值 mx。由于题目保证所有魔法值非负，"
            "只要曾经到达终点，mx 就不会停留在初始值 -1，最后据此判断是否输出 false。",
            "复杂度上界是指数级的，但地图规模很小（N<10），加上可行性剪枝完全够用；"
            "易错点在于“先加奖励再扣魔法值”的结算顺序，以及起终点不产生魔法值。",
        ],
        code_pages=[
            CodePage(
                heading="全局变量（递归过程中基本都要用到，作为参数传递太麻烦，而且很占空间）",
                bullets=[
                    "1. wked(walked) 存储每个密室是否在该次探索中走过，走过则为 1",
                    "2. mx(max) 为截止目前探索出的到达终点能得到的最大魔法值，初始化为 -1",
                    "3. sum 在每次探索中负责累加得到的魔法，以在到达终点时与 mx 比较",
                    "4. hp 在每次探索中存储当前的生命值，hp<=0 则无法继续探索",
                    "5. dx[]、dy[] 是上下左右探索时的坐标偏移量，方便用循环简化代码",
                ],
                note="（注：变量后的括号为对变量缩写名称的展开，方便理解与记忆）",
            ),
            CodePage(
                heading="递归函数 dfs(x, y, hp, sum)",
                bullets=[
                    "1. 若 (x,y) 是终点，用 sum 更新 mx 并返回",
                    "2. 否则枚举四个方向，计算下一个格子 (nx,ny)",
                    "3. 越界或已经走过则跳过；进入前按奇偶结算生命值与魔法值",
                    "4. 结算后 hp 仍大于 0 才继续递归，回溯时恢复 wked 与 sum",
                    "5. 主函数读入地图，从 (0,0) 出发，最后按 mx 是否为 -1 输出",
                ],
            ),
        ],
        tips="注意：起点和终点都是普通密室，不产生任何魔法值。",
        run_output="12",
    )
    p2 = Problem(
        assignment="函数(强化)", ptype="填空题", title="汉诺塔",
        description=(
            "汉诺塔问题：有三根柱子 A、B、C，A 柱上从下到上放着 n 个大小不同的圆盘。"
            "要求把所有圆盘移到 C 柱，每次只能移动一个盘子，且大盘不能压在小盘上。"
        ),
        input_form="输入一个整数 n（1≤n≤10）。",
        output_form="输出每一步移动，格式为 A->C。",
        samples=[Case("3", "A->C\nA->B\nC->B\nA->C\nB->A\nB->C\nA->C")],
        analysis=[
            "把 n 个盘子从 A 移到 C，可以拆成三步：先把上面 n-1 个盘子从 A 移到 B，"
            "再把最大的盘子从 A 移到 C，最后把 n-1 个盘子从 B 移到 C。",
            "三步中前两步和原问题是同一个问题，只是规模变成了 n-1，柱子角色发生了轮换，"
            "这正是递归“自己调用自己”的地方。",
            "递归出口是 n==1：直接把盘子从起始柱移到目标柱并输出即可。",
        ],
        code_pages=[CodePage(heading="", bullets=[
            "1. hanoi(n, a, b, c) 表示把 n 个盘子从 a 借助 b 移到 c",
            "2. 先递归 hanoi(n-1, a, c, b)，把上面 n-1 个盘子挪到 b",
            "3. 输出 a->c，移动最大的那个盘子",
            "4. 再递归 hanoi(n-1, b, a, c)，把 n-1 个盘子挪到 c",
        ])],
        tips="填空时注意三个参数的位置：起点、辅助柱、目标柱。",
        run_output="A->C\nA->B\nC->B\nA->C\nB->A\nB->C\nA->C",
    )
    return Deck(
        session="第五次", group="第二组 3 号", klass="计科 2304",
        name="覃禹嘉", student_id="202308010423",
        problems=[p1, p2],
        summary=[
            "搜索类题目先想清楚“状态是什么、每一步怎么转移”，再考虑剪枝，代码自然就顺了。",
            "递归不要一上来就抠细节，先相信子问题已经解决，只处理当前这一层。",
            "样例通过只是开始，学会自己造边界数据，才能真正验证程序的正确性。",
        ],
    )
